// Isikan Data Contoh ke Form
function fillDemoData(statusType) {
    const targetData = studentDatabase.find(item => item.status === statusType);
    if (targetData) {
        document.getElementById('fullName').value = targetData.name;
        document.getElementById('nicNumber').value = targetData.nic;
        document.getElementById('birthPlace').value = targetData.birthPlace;
        document.getElementById('birthDate').value = targetData.birthDate;
        
        handleFormSubmit(new Event('submit'));
    }
}

// Form Submit Handler
function handleFormSubmit(e) {
    if (e) e.preventDefault();

    const loading = document.getElementById('loadingOverlay');
    loading.style.display = 'flex';

    const nameInput = document.getElementById('fullName').value.trim();
    const nicInput = document.getElementById('nicNumber').value.trim();
    const placeInput = document.getElementById('birthPlace').value.trim();
    const dateInput = document.getElementById('birthDate').value;

    // Process Data
    setTimeout(() => {
        loading.style.display = 'none';

        // Format Tanggal
        const dateObj = new Date(dateInput);
        const options = { day: 'numeric', month: 'long', year: 'numeric' };
        const formattedDate = dateObj.toLocaleDateString('id-ID', options);

        // Cek apakah data cocok di Database
        let foundMatch = studentDatabase.find(student => 
            student.nic.toLowerCase() === nicInput.toLowerCase() || 
            student.name.toLowerCase() === nameInput.toLowerCase()
        );

        let statusResult = "PASSED";

        if (foundMatch) {
            statusResult = foundMatch.status;
        } else {
            // Penentuan acak sederhana jika nama tidak ada dalam database
            const lengthMod = nameInput.length % 3;
            if (lengthMod === 0) {
                statusResult = "PASSED";
            } else if (lengthMod === 1) {
                statusResult = "PENDING";
            } else {
                statusResult = "FAILED";
            }
        }

        let resultData = {
            name: nameInput,
            nic: nicInput,
            birthPlace: placeInput,
            formattedDate: formattedDate,
            status: statusResult
        };

        if (statusResult === "PASSED") {
            resultData.message = "Selamat! **Anda lolos ke tahap selanjutnya**. Perjalanan hebat dimulai dari satu langkah berani. Tetap semangat, berikan potensi terbaikmu, dan buktikan bahwa kamu siap menjadi bagian dari perubahan positif!";
            resultData.notice = "Selalu pantau grup **Calon Pengurus OSK 26/27** untuk informasi dan instruksi selanjutnya.";
        } else if (statusResult === "PENDING") {
            resultData.message = "Anda dijadwalkan untuk mengikuti **TES SUSULAN**. Harap mempersiapkan diri kembali dan hadir sesuai dengan waktu dan ketentuan yang ditetapkan panitia.";
            resultData.notice = "Segera hubungi panitia atau pantau pengumuman di grup **Informasi Tes Susulan OSK 26/27**.";
        } else {
            resultData.message = "Mohon maaf, Anda **BELUM LOLOS** pada Seleksi Unjuk Bakat tahun ini. Ini bukanlah akhir dari segalanya, melainkan langkah awal untuk terus berkembang dan mencoba lagi di kesempatan berikutnya!";
            resultData.notice = "Tetap menjadi pribadi yang berprestasi dan pantang menyerah di SMANKALBU.";
        }

        renderResult(resultData);
    }, 1000);
}

// Render Result UI
function renderResult(data) {
    const resultCard = document.getElementById('resultCard');
    const selectionForm = document.getElementById('selectionForm');
    const formHeader = document.getElementById('formHeader');
    const demoBar = document.getElementById('demoBar');

    // Hide Form UI elements
    selectionForm.style.display = 'none';
    formHeader.style.display = 'none';
    demoBar.style.display = 'none';

    let statusClass = '';
    let statusIcon = '';
    let statusTitle = '';
    let badgeText = '';

    if (data.status === 'PASSED') {
        statusClass = 'status-passed';
        statusIcon = 'fa-circle-check';
        statusTitle = 'SELAMAT! LOLOS SELEKSI';
        badgeText = 'LOLOS TAHAP SELANJUTNYA';
    } else if (data.status === 'PENDING') {
        statusClass = 'status-pending';
        statusIcon = 'fa-clock';
        statusTitle = 'TES SUSULAN';
        badgeText = 'DIJADWALKAN TES SUSULAN';
    } else {
        statusClass = 'status-failed';
        statusIcon = 'fa-circle-xmark';
        statusTitle = 'MOHON MAAF';
        badgeText = 'TIDAK LULUS';
    }

    resultCard.className = `result-card ${statusClass}`;
    resultCard.innerHTML = `
        <div class="result-header">
            <i class="fa-solid ${statusIcon}"></i>
            <h2>${statusTitle}</h2>
            <p style="opacity: 0.9; font-size: 0.9rem;">Hasil Seleksi Tes Wawasan Umum & Unjuk Bakat</p>
        </div>
        <div class="result-body">
            <div class="info-grid">
                <div class="info-item">
                    <span class="info-label">Nama Lengkap</span>
                    <span class="info-value">${data.name}</span>
                </div>
                <div class="info-item">
                    <span class="info-label">Nomor Induk Calon (NIC)</span>
                    <span class="info-value">${data.nic}</span>
                </div>
                <div class="info-item">
                    <span class="info-label">Tempat, Tanggal Lahir</span>
                    <span class="info-value">${data.birthPlace}, ${data.formattedDate}</span>
                </div>
            </div>

            <div class="status-box">
                <span class="status-badge-res">${badgeText}</span>
                <p class="status-notes">${data.message.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')}</p>
                ${data.notice ? `
                    <div class="group-notice">
                        <i class="fa-solid fa-bullhorn"></i>
                        <span>${data.notice.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')}</span>
                    </div>
                ` : ''}
            </div>

            <div class="action-buttons">
                <button class="btn-secondary" onclick="resetForm()">
                    <i class="fa-solid fa-arrow-left"></i> Kembali
                </button>
                <button class="btn-print" onclick="window.print()">
                    <i class="fa-solid fa-print"></i> Cetak Kartu Hasil
                </button>
            </div>
        </div>
    `;

    resultCard.style.display = 'block';
}

// Reset to Search View
function resetForm() {
    document.getElementById('resultCard').style.display = 'none';
    document.getElementById('selectionForm').style.display = 'block';
    document.getElementById('formHeader').style.display = 'block';
    document.getElementById('demoBar').style.display = 'flex';
}